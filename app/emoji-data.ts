// The emojis the picker offers: a hand-picked set of common ones, as plain data.
//
// Nothing is loaded from anywhere. An emoji is a piece of Unicode text, drawn by the reader's own
// system font, and it goes into a message as that text. Each entry is
//   [emoji, name, keywords]
// where the name is what a screen reader says and the keywords are extra words the search finds.

export interface Emoji {
  char: string;
  name: string;
  /** Lower-case words the search matches, the words of the name included. */
  words: string[];
}
export interface EmojiGroup {
  id: string;
  label: string;
  emojis: Emoji[];
}

type Row = [char: string, name: string, keywords: string];

const group = (id: string, label: string, rows: Row[]): EmojiGroup => ({
  id,
  label,
  emojis: rows.map(([char, name, keywords]) => ({
    char,
    name,
    words: [...new Set(`${name} ${keywords}`.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean))],
  })),
});

